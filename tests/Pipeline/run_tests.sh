#!/bin/bash
# Runs the MP_Pipeline pipeline tests on Linux: the counterpart of run_tests.ps1 (Windows, AVSMeter).
#
# Each *.avs scenario is run with avs_run (the test host, tests/Pipeline/avs_run.cpp, built with
# cmake -DMPP_BUILD_TESTS=ON), which requests every frame once. A scenario passes when its log has
# one " OK" line per frame; error_*.avs scenarios must fail to load with the message in their first
# line ("# expect: <text>"). A scenario stopping with Assert(false, "SKIP: <reason>") is skipped.
# "### platform" is Windows only and ignored on Linux: the scenarios with a slave of the other
# bitness run with a native slave here, except error_format_old_core (needs a newer slave core).
#
# usage: run_tests.sh <build dir> [scenario ...]
#   <build dir>: the CMake build folder (its AVS_SplitProcess/ has libmp_pipeline.so, the slave and
#                avs_run), or a folder with these files
# environment: AVS_LIBRARY (default libavisynth.so), TIMEOUT_SEC (default 600)

here="$(cd "$(dirname "$0")" && pwd)"
build="${1:?usage: run_tests.sh <build dir> [scenario ...]}"
shift
build="$(cd "$build" && pwd)"
[ -d "$build/AVS_SplitProcess" ] && build="$build/AVS_SplitProcess"
plugin="$build/libmp_pipeline.so"
host="$build/avs_run"
avs_library="${AVS_LIBRARY:-libavisynth.so}"
timeout_sec="${TIMEOUT_SEC:-600}"
frames=800 # PROPS_FRAMES in props_common.avsi

for f in "$plugin" "$plugin.slave" "$host"; do
  [ -f "$f" ] || { echo "Not found: $f"; exit 2; }
done

# needs a slave core newer than the master's: no slave of the other bitness here
cross_only="error_format_old_core"

if [ $# -gt 0 ]; then
  scenarios="$*"
else
  scenarios="$(cd "$here" && ls *.avs | sed 's/\.avs$//' | sort)"
fi

log_dir="$here/out/linux"
mkdir -p "$log_dir"
cat > "$here/_config.avsi" <<EOF
# generated by run_tests.sh
global MPP_DLL = "$plugin"
global LOG_DIR = "$log_dir/"
global OTHER_PLATFORM = "win32" # ignored on Linux: a native slave
EOF

log_names() {
  if [ "$1" = "multi_export" ]; then echo "multi_export_a multi_export_b"; else echo "$1"; fi
}

echo "=== $(uname -m) ($plugin)"
failed=0
for scenario in $scenarios; do
  case " $cross_only " in
    *" $scenario "*) printf "  %-28s SKIP (needs a newer slave core: no other platform on Linux)\n" "$scenario"; continue ;;
  esac
  logs="$(log_names "$scenario")"
  for l in $logs; do rm -f "$log_dir/$l.log"; done

  out="$log_dir/$scenario.out.txt"
  start=$(date +%s%N)
  ( cd "$here" && timeout "$timeout_sec" "$host" "$here/$scenario.avs" "$avs_library" ) > "$out" 2>&1
  rc=$?
  ms=$(( ($(date +%s%N) - start) / 1000000 ))
  if [ $rc -eq 124 ]; then
    printf "  %-28s FAIL (timeout)\n" "$scenario"; failed=$((failed + 1)); continue
  fi
  text="$(tr -d '\n' < "$out")"
  # a crash (also at the end, after every frame) is a failure: 139 = SIGSEGV
  if [[ "$scenario" != error_* && $rc -ne 0 ]] && [[ "$text" != *"SKIP: "* ]]; then
    printf "  %-28s FAIL (avs_run exit code %d)\n" "$scenario" $rc; failed=$((failed + 1)); continue
  fi

  skip="$(echo "$text" | sed -n 's/.*SKIP: \(.*\)(.*avs, line [0-9]*).*/\1/p')"
  if [ -n "$skip" ]; then
    printf "  %-28s SKIP (%s)\n" "$scenario" "$(echo "$skip" | sed 's/[[:space:]]*$//')"; continue
  fi

  problems=()
  if [[ "$scenario" == error_* ]]; then
    expect="$(head -1 "$here/$scenario.avs" | sed 's/^# expect: //' | tr -d '\r')"
    logs=""
    if [[ "$text" != *"$expect"* ]]; then
      problems+=("expected error message not found: $expect")
      problems+=("got: $(grep -m1 'Error:' "$out")")
    fi
  fi
  for l in $logs; do
    log="$log_dir/$l.log"
    if [ ! -f "$log" ]; then
      problems+=("$l.log missing")
      problems+=("avs_run: $(grep -m1 -A1 'Error:' "$out" | tr '\n' ' ')")
      continue
    fi
    lines=$(wc -l < "$log")
    bad=$(grep -vc ' OK$' "$log")
    [ "$lines" -ne "$frames" ] && problems+=("$l.log has $lines lines, expected $frames")
    [ "$bad" -gt 0 ] && problems+=("$l.log: $bad failed lines, first: $(grep -vm1 ' OK$' "$log")")
  done

  if [ ${#problems[@]} -eq 0 ]; then
    printf "  %-28s OK   (%3d.%d s)\n" "$scenario" $((ms / 1000)) $((ms % 1000 / 100))
  else
    failed=$((failed + 1))
    printf "  %-28s FAIL\n" "$scenario"
    for p in "${problems[@]}"; do echo "      $p"; done
  fi
done

rm -f "$here/_config.avsi"
if [ $failed -eq 0 ]; then echo "RESULT: OK"; else echo "RESULT: $failed FAILURE(S)"; fi
[ $failed -eq 0 ]
