<#
.SYNOPSIS
  Runs the MP_Pipeline frame property tests with AVSMeter, for x64 and/or x86 masters.

.DESCRIPTION
  For each bitness: writes _config.avsi (plugin path, log folder, platform of the
  cross-bitness slave), runs every *.avs scenario with AVSMeter and checks that its
  log has one " OK" line per frame.
  A scenario stopping with Assert(false, "SKIP: <reason>") is reported as skipped
  (e.g. it needs a newer AviSynth+ than the installed one).
  error_*.avs scenarios must fail to load: their first line "# expect: <text>" is the
  text the error message must contain.
  Needs the plugin built (Output\<platform>\<Configuration>, or a folder given with
  -PluginDir: <PluginDir>\<platform>\, e.g. a CMake / MinGW build with the other bitness pair
  copied next to it) and AviSynth+ (V8+)
  installed for the tested bitness; cross_bitness.avs needs both.

.EXAMPLE
  .\run_tests.ps1 -AvsMeterDir D:\Tools\AVSMeter
  .\run_tests.ps1 -AvsMeterDir D:\Tools\AVSMeter -Platforms x64 -Tests prefetch,reverse
  .\run_tests.ps1 -AvsMeterDir D:\Tools\AVSMeter -PluginDir D:\mpp_mingw   (x64\ and Win32\ in it)
#>
param(
  [Parameter(Mandatory = $true)] [string] $AvsMeterDir,   # folder of AVSMeter.exe / AVSMeter64.exe
  [string[]] $Platforms = @("x64", "Win32"),
  [string] $Configuration = "Release",
  [string] $PluginDir = "",                                # instead of Output\<platform>\<Configuration>: <PluginDir>\<platform>
  [string[]] $Tests = @(),                                 # scenario names, default: all
  [int] $TimeoutSec = 600,
  # record overflow mapping events (MPP_TRACE_PROPS) per scenario into out\<platform>\<scenario>.props_trace.txt;
  # needs tests\tools\bin\dbwin_listen.exe (cl /O2 /EHsc dbwin_listen.cpp) and no running DebugView
  [switch] $TraceProps
)

$ErrorActionPreference = "Stop"
$here = $PSScriptRoot
$root = Resolve-Path (Join-Path $here "..\..")
$frames = 800   # PROPS_FRAMES in props_common.avsi
$failed = 0

# Windows PowerShell's -Filter *.avs also matches *.avsi (8.3 name matching)
$scenarios = Get-ChildItem $here -Filter *.avs | Where-Object { $_.Extension -eq ".avs" } | Sort-Object Name | ForEach-Object { $_.BaseName }
if ($Tests.Count -gt 0) { $scenarios = $scenarios | Where-Object { $Tests -contains $_ } }

# log files written by a scenario (multi_export writes two)
function Get-LogNames($scenario) {
  if ($scenario -eq "multi_export") { return @("multi_export_a", "multi_export_b") }
  return @($scenario)
}

foreach ($platform in $Platforms) {
  $is64 = $platform -eq "x64"
  $meter = Join-Path $AvsMeterDir ($(if ($is64) { "AVSMeter64.exe" } else { "AVSMeter.exe" }))
  if ($PluginDir) {
    $dll = Join-Path $PluginDir "$platform\MP_Pipeline.dll"
    $label = $dll
  } else {
    $dll = Join-Path $root "Output\$platform\$Configuration\MP_Pipeline.dll"
    $label = $Configuration
  }
  if (-not (Test-Path $meter)) { throw "Not found: $meter" }
  if (-not (Test-Path $dll)) { throw "Not found: $dll (build $Configuration|$platform first)" }

  $logDir = Join-Path $here "out\$platform"
  New-Item -ItemType Directory -Force $logDir | Out-Null
  $other = if ($is64) { "win32" } else { "win64" }
  @(
    "# generated by run_tests.ps1"
    "global MPP_DLL = ""$dll"""
    "global LOG_DIR = ""$logDir\"""
    "global OTHER_PLATFORM = ""$other"""
    "global PLATFORMS_SUPPORTED = true"
  ) | Set-Content -Encoding ASCII (Join-Path $here "_config.avsi")

  Write-Host "=== $platform ($label)"
  foreach ($scenario in $scenarios) {
    $logs = Get-LogNames $scenario
    foreach ($l in $logs) { Remove-Item -ErrorAction SilentlyContinue (Join-Path $logDir "$l.log") }

    $listener = $null
    $traceFile = Join-Path $logDir "$scenario.props_trace.txt"
    if ($TraceProps) {
      $listenerExe = Join-Path $here "..\tools\bin\dbwin_listen.exe"
      if (-not (Test-Path $listenerExe)) { throw "Not found: $listenerExe" }
      $env:MPP_TRACE_PROPS = "1"
      $listener = Start-Process $listenerExe -ArgumentList ($TimeoutSec + 10), "MPP_Props" -NoNewWindow -PassThru -RedirectStandardOutput $traceFile
      Start-Sleep -Milliseconds 500
    }

    $sw = [Diagnostics.Stopwatch]::StartNew()
    # -o: single pass, no pre-scan (each frame is logged exactly once)
    $p = Start-Process -FilePath $meter -ArgumentList "`"$(Join-Path $here "$scenario.avs")`"", "-o" `
      -WorkingDirectory $here -NoNewWindow -PassThru `
      -RedirectStandardOutput (Join-Path $logDir "$scenario.meter.txt") -RedirectStandardError (Join-Path $logDir "$scenario.meter.err.txt")
    $finished = $p.WaitForExit($TimeoutSec * 1000)
    if (-not $finished) { $p.Kill() }
    $sw.Stop()
    if ($listener) {
      Start-Sleep -Milliseconds 500
      Stop-Process $listener -ErrorAction SilentlyContinue
      Remove-Item env:MPP_TRACE_PROPS
    }
    if (-not $finished) { Write-Host ("  {0,-28} FAIL (timeout)" -f $scenario); $failed++; continue }

    $problems = @()
    # AVSMeter wraps long lines at console width: compare with line breaks removed
    $meterOut = ((Get-Content -Raw -ErrorAction SilentlyContinue (Join-Path $logDir "$scenario.meter.txt")) + `
      (Get-Content -Raw -ErrorAction SilentlyContinue (Join-Path $logDir "$scenario.meter.err.txt"))) -replace "\r?\n", ""
    # a scenario not applicable to the installed AviSynth stops with Assert(false, "SKIP: <reason>")
    if ($meterOut -match "SKIP: (.+?)\s*\(.*avs, line \d+\)") {
      Write-Host ("  {0,-28} SKIP ({1})" -f $scenario, $Matches[1])
      continue
    }
    $expect = (Get-Content (Join-Path $here "$scenario.avs") -TotalCount 1) -replace "^# expect: ", ""
    if ($scenario -like "error_*") {
      # expected to fail to load, with this message
      $logs = @()
      if ($meterOut.IndexOf($expect, [StringComparison]::Ordinal) -lt 0) {
        $problems += "expected error message not found: $expect"
        if ($meterOut -match "(MP_Pipeline:.*?)(\(.*avs, line \d+\)|$)") { $problems += "got: $($Matches[1])" }
      }
    }
    foreach ($l in $logs) {
      $logFile = Join-Path $logDir "$l.log"
      if (-not (Test-Path $logFile)) { $problems += "$l.log missing"; continue }
      $lines = @(Get-Content $logFile)
      $bad = @($lines | Where-Object { $_ -notmatch " OK$" })
      if ($lines.Count -ne $frames) { $problems += "$l.log has $($lines.Count) lines, expected $frames" }
      if ($bad.Count -gt 0) { $problems += "$l.log: $($bad.Count) failed lines, first: $($bad[0])" }
    }
    $traceInfo = ""
    if ($TraceProps -and (Test-Path $traceFile)) {
      $events = @(Get-Content $traceFile | Where-Object { $_ -match "server .*overflow mapping (\d+) -> (\d+)" } | ForEach-Object {
        $from = [int64]$Matches[1]; $to = [int64]$Matches[2]
        if ($to -eq 0) { "release" } elseif ($to -gt $from) { "grow" } else { "shrink" } })
      $traceInfo = "  overflow: {0} grow, {1} shrink, {2} release" -f `
        @($events | Where-Object { $_ -eq "grow" }).Count, @($events | Where-Object { $_ -eq "shrink" }).Count, @($events | Where-Object { $_ -eq "release" }).Count
    }
    if ($problems.Count -eq 0) {
      Write-Host ("  {0,-28} OK   ({1,5:N1} s){2}" -f $scenario, $sw.Elapsed.TotalSeconds, $traceInfo)
    } else {
      $failed++
      Write-Host ("  {0,-28} FAIL" -f $scenario)
      $problems | ForEach-Object { Write-Host "      $_" }
      # a missing log means the script did not load: show AVSMeter's error
      if ($scenario -notlike "error_*" -and ($problems -match "missing$") -and $meterOut -match "Loading script\.\.\.\s*(.+?)(\(.*avs, line \d+\)|$)") {
        Write-Host "      AVSMeter: $($Matches[1].Trim())"
      }
    }
  }
}

Remove-Item -ErrorAction SilentlyContinue (Join-Path $here "_config.avsi")
if ($failed) { Write-Host "RESULT: $failed FAILURE(S)"; exit 1 }
Write-Host "RESULT: OK"
